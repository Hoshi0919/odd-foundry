"""Active strain-cycle work extraction engine and cargo booster."""

import numpy as np
from odd.constitutive import OddElasticMedium


class StrainEngine:
    """Extracts continuous mechanical work from closed strain-space cycles in odd metamaterials.

    Under cyclic boundary driving:
        eps_s(t) = eps_0 * cos(Omega * t)
        eps_a(t) = eps_0 * sin(Omega * t)

    The continuous work extraction rate is:
        P(t) = sigma_s * (d eps_s / dt) + sigma_a * (d eps_a / dt) = A_o * Omega * eps_0^2 > 0

    Work extracted over N cycles is transferred directly to accelerate passing cargo pallets.
    """

    def __init__(
        self,
        medium: OddElasticMedium | None = None,
        strain_amplitude: float = 0.12,
        frequency_hz: float = 20.0,
        chamber_volume: float = 1.0,
    ):
        self.medium = medium or OddElasticMedium(bulk_modulus=10.0, shear_modulus=5.0, odd_modulus=3.0)
        self.eps_0 = float(strain_amplitude)
        self.freq = float(frequency_hz)
        self.omega = 2.0 * np.pi * self.freq
        self.volume = float(chamber_volume)

    @property
    def cycle_period(self) -> float:
        return 1.0 / self.freq

    @property
    def work_per_cycle(self) -> float:
        """Total mechanical work generated per cycle per unit volume."""
        return self.medium.compute_work_extracted_analytical(self.eps_0, self.eps_0)

    @property
    def average_power_output(self) -> float:
        """Net continuous mechanical power generated by the engine chamber."""
        return self.work_per_cycle * self.freq * self.volume

    def boost_cargo(self, cargo_mass: float = 2.0, entry_velocity: float = 1.0, dwell_cycles: float = 5.0) -> dict:
        """Calculates kinetic energy and velocity boost for cargo traversing the active chamber."""
        if cargo_mass <= 0:
            raise ValueError("Cargo mass must be positive")
        if dwell_cycles < 0:
            raise ValueError("Dwell cycles cannot be negative")

        total_work = self.work_per_cycle * dwell_cycles * self.volume
        initial_ke = 0.5 * cargo_mass * (entry_velocity ** 2)
        final_ke = initial_ke + total_work
        exit_velocity = float(np.sqrt(2.0 * final_ke / cargo_mass))

        return {
            'entry_velocity': float(entry_velocity),
            'exit_velocity': exit_velocity,
            'initial_kinetic_energy': float(initial_ke),
            'final_kinetic_energy': float(final_ke),
            'work_transferred': float(total_work),
            'boost_factor': exit_velocity / (entry_velocity if entry_velocity > 1e-6 else 1e-6),
        }
